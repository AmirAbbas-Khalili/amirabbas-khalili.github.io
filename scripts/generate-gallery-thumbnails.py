"""Generate small previews while preserving all full-size gallery originals.

Run after `npm run build`, using Python with Pillow installed. It reads the
rendered gallery data rather than duplicating the content collections.
Commit the generated previews and src/data/gallery-thumbnails.ts with the site.
"""
from pathlib import Path
from html.parser import HTMLParser
from io import BytesIO
import hashlib
import json
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
if not (ROOT / 'src/pages').exists():
    ROOT = Path('C:/Users/Amir/Desktop/apply/Website v2')

class Galleries(HTMLParser):
    def __init__(self):
        super().__init__()
        self.originals = set()
    def handle_starttag(self, tag, attrs):
        attributes = dict(attrs)
        if 'data-work-gallery' not in attributes or 'data-photos' not in attributes:
            return
        for photo in json.loads(attributes['data-photos']):
            src = photo['src']
            if src.startswith('/images/') and photo.get('thumbnail', src) == src:
                self.originals.add(src)

galleries = Galleries()
for html in (ROOT / 'dist').rglob('index.html'):
    if 'fa' not in html.relative_to(ROOT / 'dist').parts:
        galleries.feed(html.read_text(encoding='utf-8'))

if not galleries.originals:
    raise RuntimeError('No full-size gallery previews found. Build the site first.')

destination = ROOT / 'public/images/gallery-thumbnails'
destination.mkdir(parents=True, exist_ok=True)
previews = {}
measurements = []
for src in sorted(galleries.originals):
    original = (ROOT / 'public' / src.lstrip('/')).resolve()
    if not original.is_relative_to((ROOT / 'public/images').resolve()):
        raise ValueError(f'Invalid image path: {src}')
    content = original.read_bytes()
    original_hash = hashlib.sha256(content).hexdigest()
    with Image.open(BytesIO(content)) as source:
        preview = ImageOps.exif_transpose(source)
        preview = preview.convert('RGBA' if 'A' in preview.getbands() else 'RGB')
        preview.thumbnail((720, 720), Image.Resampling.LANCZOS)
        target = destination / f'{original.stem}-{original_hash[:12]}.webp'
        preview.save(target, 'WEBP', quality=88, method=6)
        previews[src] = {
            'src': '/images/gallery-thumbnails/' + target.name,
            'width': preview.width,
            'height': preview.height,
        }
    assert hashlib.sha256(original.read_bytes()).hexdigest() == original_hash
    measurements.append({'original':src, 'originalBytes':len(content),
                         'previewBytes':target.stat().st_size, **previews[src]})

module = '''// Generated by scripts/generate-gallery-thumbnails.py.
// Originals are retained exclusively for the gallery's full-size view.
export const GALLERY_THUMBNAILS: Record<string, {src:string; width:number; height:number}> = '''
module += json.dumps(previews, ensure_ascii=False, indent=2) + ';\n'
module += '''
export function galleryPreview(src:string): {src:string; width?:number; height?:number} {
  return GALLERY_THUMBNAILS[src] ?? {src};
}
export function galleryThumbnail(src:string): string {
  return galleryPreview(src).src;
}
'''
(ROOT / 'src/data/gallery-thumbnails.ts').write_text(module, encoding='utf-8')
original_total = sum(row['originalBytes'] for row in measurements)
preview_total = sum(row['previewBytes'] for row in measurements)
print(json.dumps({'previews':len(measurements), 'originalBytes':original_total,
                  'previewBytes':preview_total,
                  'reductionPercent':round((1-preview_total/original_total)*100,2)}, indent=2))
(ROOT / 'docs/homepage-previews/gallery-thumbnail-sizes.json').write_text(
    json.dumps(measurements, indent=2)+'\n', encoding='utf-8')
